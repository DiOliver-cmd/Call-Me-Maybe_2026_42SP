"""Token index benchmark for the decoder's per-step candidate lookup (T2.3).

Run manually with: ``uv run python -m experiments.index_benchmark``

Loads the real model through the public SDK API, reuses
``.cache/token_text.json`` (building it if absent), builds the first-character
index and compares it with a naive scan over every allowed id. Writes the
deterministic report ``experiments/vocab_index.md`` (no timestamps or
machine-specific paths). Not collected by pytest because pytest scans only
``tests/``.
"""

from __future__ import annotations

import statistics
import time
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from llm_sdk import Small_LLM_Model

from src.vocab import (
    TokenizerVocab,
    build_token_index,
    build_token_text_via_decode,
    excluded_token_ids,
    load_token_text_cache,
    parse_tokenizer_json,
    save_token_text_cache,
)

CACHE_PATH = Path(".cache/token_text.json")
REPORT_PATH = Path("experiments/vocab_index.md")
RUNS = 5

# Character and prefix constraints a typical JSON state can demand.
CONSTRAINTS = (
    "{",
    '"',
    ":",
    ",",
    "}",
    " ",
    "a",
    "0",
    "\\",
    '{"',
    '"na',
    '{"na',
    '{"name"',
)


def _load_texts(model: Any, tokenizer: TokenizerVocab) -> dict[int, str]:
    """Reuse the decoded cache when it covers every id, else rebuild it."""
    ids = sorted(tokenizer.token_text)
    if CACHE_PATH.exists():
        cached = load_token_text_cache(CACHE_PATH)
        if set(cached) >= set(ids):
            return cached
    texts = build_token_text_via_decode(model, ids)
    save_token_text_cache(CACHE_PATH, texts)
    return texts


def _naive_starting_with(
    token_ids: Sequence[int],
    texts: dict[int, str],
    prefix: str,
) -> tuple[int, ...]:
    """Scan every allowed id and keep the ones whose text starts with prefix."""
    return tuple(
        token_id
        for token_id in token_ids
        if texts[token_id].startswith(prefix)
    )


def _median_seconds(fn: Callable[[], object], runs: int = RUNS) -> float:
    """Return the median wall time of ``runs`` calls to ``fn``."""
    samples: list[float] = []
    for _ in range(runs):
        start = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - start)
    return statistics.median(samples)


def _code(text: str) -> str:
    return f"`{text}`"


def _format_speedup(speedup: float) -> str:
    if speedup == float("inf"):
        return "inf"
    return f"{speedup:.0f}x"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    """Render a deterministic Markdown table."""
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def main() -> int:
    model = Small_LLM_Model()
    tokenizer_path = model.get_path_to_tokenizer_file()
    tokenizer = parse_tokenizer_json(tokenizer_path)
    texts = _load_texts(model, tokenizer)

    start = time.perf_counter()
    index = build_token_index(tokenizer, texts)
    build_seconds = time.perf_counter() - start

    lookup_rows: list[list[str]] = []
    for constraint in CONSTRAINTS:
        naive_result = _naive_starting_with(
            index.allowed_ids, texts, constraint
        )
        indexed_result = index.tokens_starting_with(constraint)
        if naive_result != indexed_result:
            raise RuntimeError(
                f"index mismatch for constraint {constraint!r}"
            )

        naive_seconds = _median_seconds(
            lambda: _naive_starting_with(
                index.allowed_ids, texts, constraint
            )
        )
        indexed_seconds = _median_seconds(
            lambda: index.tokens_starting_with(constraint)
        )
        if indexed_seconds > 0:
            speedup = naive_seconds / indexed_seconds
        else:
            speedup = float("inf")
        lookup_rows.append(
            [
                _code(repr(constraint)),
                str(len(indexed_result)),
                f"{naive_seconds * 1000:.3f}",
                f"{indexed_seconds * 1000:.3f}",
                _format_speedup(speedup),
            ]
        )

    lookup_table = _table(
        ["constraint", "candidates", "naive ms", "indexed ms", "speedup"],
        lookup_rows,
    )

    lines = [
        "# Token index benchmark (T2.3)",
        "",
        "Deterministic report generated by "
        "`uv run python -m experiments.index_benchmark`.",
        "",
        "## Build",
        "",
        _table(
            ["Quantity", "Value"],
            [
                ["mapped token ids", str(tokenizer.vocab_size)],
                ["allowed tokens", str(len(index.allowed_ids))],
                [
                    "excluded added control tokens",
                    str(len(excluded_token_ids(tokenizer))),
                ],
                ["build time", f"{build_seconds:.3f} s"],
                ["timed runs per row", f"{RUNS} (median)"],
            ],
        ),
        "",
        "## Prefix lookup",
        "",
        "Naive scans every allowed id with `str.startswith`; indexed uses "
        "`by_first_char` and then runs the same check on the narrowed bucket.",
        "",
        lookup_table,
        "",
        "## Deferred cache",
        "",
        "The `(state_id, token_id) -> next_state_id | None` cache is deferred: "
        "it needs DFA state ids, which do not exist until T4. Revisit it in "
        "T8.3 profiling, after the decoder exists, instead of guessing the "
        "state model now.",
        "",
        "## Run",
        "",
        "```bash",
        "uv run python -m experiments.index_benchmark",
        "```",
        "",
    ]

    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")

    print(
        f"vocab_size={tokenizer.vocab_size} "
        f"allowed={len(index.allowed_ids)} "
        f"build_seconds={build_seconds:.3f}"
    )
    print(lookup_table)
    print(f"wrote {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
